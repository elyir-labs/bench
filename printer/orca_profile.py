# Slicing like their own prints (docs/slicer-profile.md): the profile a G-code file from OrcaSlicer carries.
#
# Every file Orca writes ends with its whole profile, resolved: "; CONFIG_BLOCK_START", one "; key = value" line
# per setting, "; CONFIG_BLOCK_END". This reads it back into the three presets Orca slices with (machine, process,
# filament), groups a printer's files by the profile they were made with, and checks a profile against Klipper.
# Which key goes in which preset, and which values are lists, comes from slicer/orca_keys.json
# (scripts/orca-keys.py, from Orca's own source).
#
# Standard library only and nothing but reading: the Moonraker component (printer_intent.py) and the tests both
# import it.
#
# This file may be distributed under the terms of the GNU GPLv3 license.

from __future__ import annotations

import hashlib
import json
import os
import re
from typing import Any, Dict, Iterable, List, Optional

TAIL = 256 * 1024          # the block is about 40 KB, after the moves and the totals
HEAD = 8 * 1024            # the generator line and our own marker are in the first few lines
MARKER = "; sliced by Elyir Bench"   # slicer/elyir_bench_slice.py writes it: never learn from our own files
SLICERS = ("OrcaSlicer",)  # whose block this can read (Bambu Studio's is close, but its printers don't run Klipper)
NAMES = {"machine": "printer_settings_id", "process": "print_settings_id", "filament": "filament_settings_id"}
AGREE = 0.8                # one profile in at least 80% of the recent files is the person's
RECENT = 20
BED_SLACK = 2.0            # mm between the bed Orca slices for and Klipper's axis_maximum
# Klipper's own commands a start G-code may begin with, besides G/M/T codes and the printer's macros
KLIPPER_COMMANDS = {"BED_MESH_CALIBRATE", "BED_MESH_PROFILE", "BED_MESH_CLEAR", "QUAD_GANTRY_LEVEL", "Z_TILT_ADJUST",
                    "SET_PRESSURE_ADVANCE", "SET_VELOCITY_LIMIT", "SET_GCODE_OFFSET", "SET_FAN_SPEED",
                    "SET_HEATER_TEMPERATURE", "TEMPERATURE_WAIT", "SET_PRINT_STATS_INFO", "SAVE_GCODE_STATE",
                    "RESTORE_GCODE_STATE", "CLEAR_PAUSE", "EXCLUDE_OBJECT_DEFINE", "SET_RETRACTION",
                    "SET_IDLE_TIMEOUT", "SET_LED", "STATUS", "RESPOND"}


# ── which preset each key belongs to ─────────────────────────────────────────

def keys_file() -> Optional[str]:
    """slicer/orca_keys.json, from the release this file is linked from (Moonraker loads it through a link in its
    components folder), or beside it."""
    here = os.path.dirname(os.path.abspath(__file__))
    real = os.path.dirname(os.path.realpath(__file__))
    for path in (os.path.join(real, "..", "slicer", "orca_keys.json"), os.path.join(here, "orca_keys.json"),
                 os.path.join(here, "..", "slicer", "orca_keys.json")):
        if os.path.isfile(path):
            return os.path.normpath(path)
    return None


def load_keys(path: Optional[str] = None) -> Dict[str, Any]:
    """{"kind": {key: machine | process | filament}, "lists", "strings", "extruder", "nil": sets,
    "lists_since": {key: version}, "orca": [versions]} (scripts/orca-keys.py says what each is)."""
    path = path or keys_file()
    if not path:
        raise FileNotFoundError("slicer/orca_keys.json isn't there")
    with open(path) as f:
        d = json.load(f)
    kind = {k: kind for kind in NAMES for k in d.get(kind, [])}
    return {"kind": kind, "lists": set(d.get("lists", [])), "strings": set(d.get("strings", [])),
            "extruder": set(d.get("extruder", [])), "nil": set(d.get("nil", [])),
            "lists_since": dict(d.get("lists_since", {})), "orca": d.get("orca", [])}


def _version(v: Optional[str]) -> List[int]:
    return [int(x) for x in re.findall(r"\d+", v or "")[:3]]


# ── reading a file ───────────────────────────────────────────────────────────

_GENERATED = re.compile(r"^;\s*generated by (\S+) (\S+)", re.M)
_LINE = re.compile(r"^; ([A-Za-z0-9_]+) = ?(.*)$")
_USED = re.compile(r"^; filament used \[mm\] = (.*)$", re.M)


def read(path: str) -> Optional[Dict[str, Any]]:
    """The settings block at the end of a G-code file as {key: raw text}, with who made it. None when there's no
    block Orca wrote (Cura, PrusaSlicer, a file cut short) or it can't be read.
        {"path", "modified", "block", "slicer": "OrcaSlicer 2.3.1", "ours": bool, "used": [filament index] | None}"""
    try:
        with open(path, "rb") as f:
            head = f.read(HEAD).decode("utf-8", "replace")
            size = os.fstat(f.fileno()).st_size
            f.seek(max(0, size - TAIL))
            tail = f.read().decode("utf-8", "replace")
            modified = os.fstat(f.fileno()).st_mtime
    except OSError:
        return None
    gen = _GENERATED.search(head)
    if not gen or gen.group(1) not in SLICERS:
        return None
    start = tail.rfind("; CONFIG_BLOCK_START")
    end = tail.find("; CONFIG_BLOCK_END", start)
    if start < 0 or end < 0:
        return None
    block: Dict[str, str] = {}
    for line in tail[start:end].splitlines()[1:]:
        m = _LINE.match(line.rstrip("\r"))
        if m:
            block.setdefault(m.group(1), m.group(2))
    used = None
    m = _USED.search(tail, 0, start)
    if m:
        try:
            used = [i for i, mm in enumerate(m.group(1).split(",")) if float(mm) > 0]
        except ValueError:
            used = None
    return {"path": path, "modified": modified, "block": block, "slicer": f"{gen.group(1)} {gen.group(2)}",
            "ours": MARKER in head, "used": used}


def version_of(f: Dict[str, Any]) -> str:
    """'2.3.1' from 'OrcaSlicer 2.3.1'."""
    return str(f.get("slicer") or "").partition(" ")[2]


def ours(f: Optional[Dict[str, Any]]) -> bool:
    """A file Elyir Bench sliced itself (the marker near its top): never learned from."""
    return bool(f and f.get("ours"))


# ── values, the way Orca writes them ─────────────────────────────────────────

def unescape(raw: str) -> str:
    """One text value: \\n, \\r, \\" and \\\\ back to what they stand for (Orca's unescape_string_cstyle)."""
    out, i = [], 0
    while i < len(raw):
        c = raw[i]
        if c == "\\" and i + 1 < len(raw):
            i += 1
            c = {"n": "\n", "r": "\r"}.get(raw[i], raw[i])
        out.append(c)
        i += 1
    return "".join(out)


def split_strings(raw: str) -> List[str]:
    """A list of text: "a";"b";c, quoted when it has spaces or escapes (Orca's unescape_strings_cstyle)."""
    if raw == "":
        return []
    out: List[str] = []
    i, n = 0, len(raw)
    while True:
        while i < n and raw[i] in " \t":
            i += 1
        buf = []
        if i < n and raw[i] == '"':
            i += 1
            while i < n and raw[i] != '"':
                c = raw[i]
                if c == "\\" and i + 1 < n:
                    i += 1
                    c = {"n": "\n", "r": "\r"}.get(raw[i], raw[i])
                buf.append(c)
                i += 1
            i += 1                                   # the closing quote
        else:
            while i < n and raw[i] != ";":
                buf.append(raw[i])
                i += 1
        out.append("".join(buf))
        while i < n and raw[i] in " \t":
            i += 1
        if i >= n:
            return out
        i += 1                                       # the semicolon
        if i >= n:
            out.append("")                           # "a;" is a then an empty one
            return out


def is_list(key: str, keys: Dict[str, Any], version: Optional[str] = None) -> bool:
    """Whether Orca keeps this key as a list; for a file from an older Orca, as that Orca did (lists_since)."""
    if key not in keys["lists"]:
        return False
    since = keys["lists_since"].get(key)
    return not (since and version and _version(version) < _version(since))


def value(key: str, raw: str, keys: Dict[str, Any], version: Optional[str] = None) -> Any:
    """A block value as an Orca JSON preset holds it: a list of strings for a list, a string otherwise."""
    if key in keys["strings"]:
        return split_strings(raw)
    if is_list(key, keys, version):
        return raw.split(",") if raw != "" else []
    return unescape(raw)


def presets(block: Dict[str, str], keys: Dict[str, Any], tool: Optional[int] = None,
            version: Optional[str] = None) -> Dict[str, Dict[str, Any]]:
    """The block as three flat Orca presets, each named from the block's own *_settings_id. A file made with several
    filaments carries each filament setting once per filament: `tool` picks one (the first by default). `version`
    is the Orca that wrote the file ("2.3.1"), for the few keys that were single before."""
    out: Dict[str, Dict[str, Any]] = {k: {} for k in NAMES}
    t = tool or 0
    nozzles = max(1, len(block.get("nozzle_diameter", "").split(",")))
    for key, raw in block.items():
        kind = keys["kind"].get(key)
        if kind is None:
            continue
        v = value(key, raw, keys, version)
        if kind == "filament" and isinstance(v, list):
            v = [v[t] if t < len(v) else (v[0] if v else "")]
        elif key in keys["extruder"] and isinstance(v, list) and len(v) > nozzles:
            v = v[:nozzles]                           # one per nozzle: Orca writes the filament colours here
        out[kind][key] = v
    for key in keys["nil"]:                           # a filament override that isn't set isn't written
        if keys["kind"].get(key) == "filament":
            out["filament"].setdefault(key, ["nil"])
    names = names_of(block, t)
    for kind, preset in out.items():
        preset["name"] = names[kind]
        preset[NAMES[kind]] = [names[kind]] if kind == "filament" else names[kind]
        preset["type"] = kind
        preset["from"] = "User"
        preset["instantiation"] = "true"
    return out


def names_of(block: Dict[str, str], tool: int = 0) -> Dict[str, str]:
    fil = split_strings(block.get("filament_settings_id", ""))
    return {"machine": unescape(_unquote(block.get("printer_settings_id", ""))) or "Learned printer",
            "process": unescape(_unquote(block.get("print_settings_id", ""))) or "Learned process",
            "filament": (fil[tool] if tool < len(fil) else (fil[0] if fil else "")) or "Learned filament"}


def _unquote(raw: str) -> str:
    return raw[1:-1] if len(raw) > 1 and raw[0] == raw[-1] == '"' else raw


# ── a printer's files, by profile ────────────────────────────────────────────

def bed_of(block: Dict[str, str]) -> Optional[List[float]]:
    """[x, y] in mm: the far corner of printable_area."""
    try:
        pts = [[float(c) for c in p.split("x")] for p in block.get("printable_area", "").split(",") if p]
        return [round(max(p[0] for p in pts), 1), round(max(p[1] for p in pts), 1)] if pts else None
    except (ValueError, IndexError):
        return None


def nozzle_of(block: Dict[str, str]) -> Optional[float]:
    try:
        return float(block.get("nozzle_diameter", "").split(",")[0])
    except ValueError:
        return None


def start_word(gcode: str) -> str:
    """The first command of a start G-code ("PRINT_START"), skipping comments and template lines."""
    for line in gcode.splitlines():
        line = line.split(";", 1)[0].strip()
        if not line or line.startswith(("{", "[")):
            continue
        return line.split()[0].upper()
    return ""


def profile_id(block: Dict[str, str]) -> str:
    """Files with the same machine, process, nozzle and bed are one profile."""
    names = names_of(block)
    same = json.dumps([names["machine"], names["process"], nozzle_of(block), bed_of(block)])
    return hashlib.sha1(same.encode()).hexdigest()[:8]


def _short(slicer: str) -> str:
    """'OrcaSlicer 2.3.1' -> 'OrcaSlicer 2.3'."""
    name, _, version = slicer.partition(" ")
    return f"{name} {'.'.join(version.split('.')[:2])}".strip()


def _tools(f: Dict[str, Any]) -> List[int]:
    """The filaments a file printed with: from its totals, or the first when it doesn't say."""
    return f["used"] if f.get("used") else [0]


def group(files: Iterable[Optional[Dict[str, Any]]]) -> List[Dict[str, Any]]:
    """Files (from read) by profile, the profile with the newest file first. Each: how many files, the newest,
    which Orca versions, and per material (filament_type) the newest file's filament preset. `source` says which
    file (and which filament in it) each preset is learned from."""
    readable = sorted((f for f in files if f and f.get("block") and not ours(f)), key=lambda f: -f["modified"])
    out: Dict[str, Dict[str, Any]] = {}
    for f in readable:
        b = f["block"]
        pid = profile_id(b)
        p = out.get(pid)
        if p is None:                                 # the newest file of this profile: its machine and process
            names = names_of(b)
            p = out[pid] = {
                "id": pid, "printer": unescape(_unquote(b.get("printer_model", ""))) or names["machine"],
                "machine": names["machine"], "process": names["process"], "nozzle": nozzle_of(b), "bed": bed_of(b),
                "files": 0, "slicer": _short(f["slicer"]), "slicers": [], "newest": int(f["modified"]),
                "materials": {}, "start": start_word(unescape(b.get("machine_start_gcode", ""))),
                "plate": unescape(b.get("curr_bed_type", "")) or None,
                "source": {"machine": f["path"], "materials": {}},
            }
        p["files"] += 1
        if _short(f["slicer"]) not in p["slicers"]:
            p["slicers"].append(_short(f["slicer"]))
        types = split_strings(b.get("filament_type", ""))
        counted = set()
        for t in _tools(f):
            if t >= len(types) or not types[t] or types[t].upper() in counted:
                continue
            material = types[t].upper()
            counted.add(material)
            if material not in p["materials"]:        # the newest file with this material: its filament preset
                p["materials"][material] = {"preset": names_of(b, t)["filament"], "files": 0}
                p["source"]["materials"][material] = [f["path"], t]
            p["materials"][material]["files"] += 1
    return sorted(out.values(), key=lambda p: -p["newest"])


def agreed(profiles: List[Dict[str, Any]], files: Iterable[Optional[Dict[str, Any]]]) -> Optional[str]:
    """The id the recent files agree on: the only profile, or one in at least 80% of the last 20 files."""
    if len(profiles) == 1:
        return profiles[0]["id"]
    recent = sorted((f for f in files if f and f.get("block") and not ours(f)), key=lambda f: -f["modified"])[:RECENT]
    if not recent:
        return None
    counts: Dict[str, int] = {}
    for f in recent:
        pid = profile_id(f["block"])
        counts[pid] = counts.get(pid, 0) + 1
    pid, n = max(counts.items(), key=lambda kv: kv[1])
    return pid if n >= AGREE * len(recent) else None


# ── does it fit this printer ─────────────────────────────────────────────────

def checks(profile: Dict[str, Any], klipper: Dict[str, Any]) -> Dict[str, Any]:
    """The bed against Klipper's limits (toolhead.axis_maximum, within 2 mm) and the start G-code's first command
    against the commands Klipper has. None for what can't be known yet (Klipper not ready).
        klipper: {"axis_maximum": [x, y, z, e] | None, "macros": ["PRINT_START", ...] | None}"""
    out: Dict[str, Any] = {"bed_ok": None, "bed_klipper": None, "start_ok": None}
    axis = klipper.get("axis_maximum")
    if axis and len(axis) >= 2:
        out["bed_klipper"] = [round(float(axis[0]), 1), round(float(axis[1]), 1)]
        bed = profile.get("bed")
        out["bed_ok"] = bool(bed) and all(abs(bed[i] - out["bed_klipper"][i]) <= BED_SLACK for i in (0, 1))
    macros = klipper.get("macros")
    if macros is not None:
        word = profile.get("start") or ""
        out["start_ok"] = (not word or word in {m.upper() for m in macros} or word in KLIPPER_COMMANDS
                           or re.fullmatch(r"[GMT]\d+(\.\d+)?", word) is not None)
    return out


def checks_pass(c: Dict[str, Any]) -> bool:
    return c.get("bed_ok") is True and c.get("start_ok") is True


def macros_of(objects: Iterable[str]) -> List[str]:
    """Klipper's macros from its object list ("gcode_macro PRINT_START")."""
    return [o.split(" ", 1)[1] for o in objects if o.startswith("gcode_macro ") and " " in o]


# ── what the component says, and what it writes (docs/slicer-profile.md) ─────

PUBLIC = ("id", "printer", "machine", "process", "nozzle", "bed", "files", "slicer", "slicers", "newest", "materials",
          "start", "plate")


def answer(profiles: List[Dict[str, Any]], files: List[Optional[Dict[str, Any]]], printer: Optional[Dict[str, Any]],
           saved: Dict[str, Any], klipper: Dict[str, Any]) -> Dict[str, Any]:
    """GET /printer/intent/profile, from the profiles found, printer.json as it is (None: not there), what's kept in
    Moonraker's database ({told, keep}) and Klipper. `auto` (not for the app) is the id to start using by itself:
    printer.json isn't hand-made and isn't learned yet, the recent files agree and that profile passes its checks."""
    yours = isinstance(printer, dict) and "learned" not in printer
    learned = (printer or {}).get("learned") if isinstance(printer, dict) and not yours else None
    using = learned.get("id") if isinstance(learned, dict) else None
    found = []
    for p in profiles:
        f = {k: p.get(k) for k in PUBLIC}
        f["checks"] = checks(p, klipper)
        found.append(f)
    by_id = {f["id"]: f for f in found}
    out: Dict[str, Any] = {"state": "none", "told": bool(saved.get("told")), "using": using, "found": found,
                           "bed_klipper": checks({}, klipper)["bed_klipper"], "newer": None, "auto": None}
    if yours:
        out["state"] = "yours"
    elif using:
        out["state"] = "using"
        cur = by_id.get(using)
        # files newer than its own, and than the moment it was picked: what was there to pick from isn't news
        since = max(cur["newest"] if cur else 0, learned.get("at") or 0)
        keep = set(saved.get("keep") or [])
        newer = [f for f in found if f["id"] != using and f["newest"] > since and f["id"] not in keep
                 and f["checks"]["bed_ok"] is not False and f["checks"]["start_ok"] is not False]
        if newer:
            out["state"], out["newer"] = "newer", newer[0]["id"]
    elif found:
        out["state"] = "ask"
        pick = agreed(profiles, files)
        if pick and checks_pass(by_id[pick]["checks"]):
            out["auto"] = pick
    return out


def preset_file(name: str) -> str:
    """The file a preset is kept in, named after it (as slicer/export_presets.py names them)."""
    return name.replace("/", "_") + ".json"


def learned(profile: Dict[str, Any], read_file, keys: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    """The presets to write for a profile, {file name: preset}: the machine and process from its newest file, and
    each material's filament from the newest file printed with it. read_file(path) gives read()'s answer."""
    src = profile["source"]
    out: Dict[str, Dict[str, Any]] = {}
    f = read_file(src["machine"])
    if not f:
        raise ValueError(f"{os.path.basename(src['machine'])} can't be read any more")
    both = presets(f["block"], keys, _tools(f)[0], version_of(f))
    for kind in ("machine", "process"):
        out[preset_file(both[kind]["name"])] = both[kind]
    for material, (path, tool) in src["materials"].items():
        g = read_file(path)
        if not g:
            continue
        fil = presets(g["block"], keys, tool, version_of(g))["filament"]
        out[preset_file(fil["name"])] = fil
    return out


def printer_json(profile: Dict[str, Any], tools: int, at: float, gcodes: str = "",
                 start_macro: bool = False) -> Dict[str, Any]:
    """elyir-bench-slicer/printer.json for a learned profile. `learned` marks it as written here (a printer.json
    without it is the person's own and never touched); from_files are the files its presets came from."""
    src = profile["source"]
    paths = [src["machine"]] + [p for p, _ in src["materials"].values()]
    rel = [os.path.relpath(p, gcodes) if gcodes else os.path.basename(p) for p in dict.fromkeys(paths)]
    out: Dict[str, Any] = {"machine": profile["machine"], "process": profile["process"]}
    if profile.get("plate"):
        out["plate"] = profile["plate"]
    out["tools"] = max(1, int(tools))
    out["materials"] = {m: v["preset"] for m, v in profile["materials"].items()}
    if start_macro:
        out["start_macro"] = True
    out["learned"] = {"id": profile["id"], "at": int(at), "from_files": rel}
    return out
