"""Slicing like their own prints (docs/slicer-profile.md): reading the profile at the end of an OrcaSlicer G-code file
back into the three presets, grouping a printer's files by profile, and checking a profile against Klipper. Small
made-up files cover every way Orca writes a value; the real check against a printer's files and its frozen presets
is in the slicer-profile doc ("As built on the printer's side")."""

import os
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import orca_profile as op  # noqa: E402

KEYS = op.load_keys()

# One of each shape, as Orca 2.3.1 writes them
SETTINGS = {
    "printer_settings_id": "My Voron",
    "print_settings_id": "0.20mm Standard @Voron",
    "filament_settings_id": '"Generic PLA @Voron";"Fancy PETG @Voron";"Generic PLA @Voron"',
    "printer_model": "Voron 2.4 300",
    "layer_height": "0.2",                                   # a number
    "sparse_infill_density": "15%",                          # a percent
    "enable_support": "0",                                   # a bool
    "nozzle_diameter": "0.4",                                # a list of one number
    "machine_max_speed_x": "500,200",                        # a list of numbers
    "printable_area": "0x0,300x0,300x300,0x300",             # points
    "bed_exclude_area": "",                                  # an empty list
    "bed_mesh_min": "-99999,-99999",                         # one point: single
    "thumbnails": "48x48/PNG,300x300/PNG",                   # single text with commas
    "z_hop_types": "Normal Lift",                            # a list of one (per nozzle)
    "nozzle_type": "hardened_steel",                         # single before 2.4.2, a list from it
    "extruder_colour": "#FF0000;#00FF00;#0000FF",            # per nozzle, but Orca writes the filament colours
    "machine_start_gcode": r'PRINT_START BED=[bed_temperature_initial_layer_single] TOOL=[initial_tool]\nM117 \"go\" C:\\x',
    "before_layer_change_gcode": r";BEFORE_LAYER_CHANGE\n;[layer_z]\nG92 E0\n",
    "filament_type": "PLA;PETG;PLA",
    "nozzle_temperature": "210,240,215",
    "filament_colour": "#FF0000;#00FF00;#0000FF",             # the project's, not a preset's
    "default_filament_colour": ";;",                         # three empty texts
    "filament_start_gcode": r'"; Filament gcode\n";"; Filament gcode\n";"; Filament gcode\n"',
    "small_area_infill_flow_compensation_model": r'0,0;"\n0.2,0.4444";"\n10,1"',   # a process list of text
    "filament_retraction_length": "1,nil,nil",               # an override, set for one filament only
    "curr_bed_type": "Textured PEI Plate",
    "different_settings_to_system": "layer_height;;;;",      # bookkeeping, not a setting
    "wipe_tower_x": "165",
}


def gcode(path, settings=None, generator="OrcaSlicer 2.3.1", marker=False, used="12.30, 0.00, 0.00", mtime=None,
          block=True):
    s = dict(SETTINGS, **(settings or {}))
    lines = ["; HEADER_BLOCK_START", f"; generated by {generator} on 2026-09-30 at 10:00:00"]
    if marker:
        lines.append(op.MARKER)
    lines += ["; total layer number: 10", "; HEADER_BLOCK_END", "", "G28", "G1 X10 Y10 E1", "; EXECUTABLE_BLOCK_END", ""]
    if used is not None:
        lines += [f"; filament used [mm] = {used}", "; total filament used [g] = 3.5", ""]
    if block:
        lines += ["; CONFIG_BLOCK_START"] + [f"; {k} = {v}" for k, v in s.items()] + ["; CONFIG_BLOCK_END", ""]
    Path(path).write_text("\n".join(lines))
    if mtime:
        os.utime(path, (mtime, mtime))
    return str(path)


def test_read_finds_the_block_the_generator_and_which_filaments_printed(tmp_path):
    f = op.read(gcode(tmp_path / "a.gcode", used="0.00, 41.20, 0.00"))
    assert f["slicer"] == "OrcaSlicer 2.3.1" and op.version_of(f) == "2.3.1"
    assert f["block"]["layer_height"] == "0.2" and f["block"]["bed_exclude_area"] == ""
    assert f["used"] == [1] and not op.ours(f)
    assert op.ours(op.read(gcode(tmp_path / "b.gcode", marker=True)))
    assert op.read(gcode(tmp_path / "c.gcode", used=None))["used"] is None


def test_files_without_an_orca_block_give_nothing(tmp_path):
    assert op.read(gcode(tmp_path / "prusa.gcode", generator="PrusaSlicer 2.8.1")) is None
    assert op.read(gcode(tmp_path / "cut.gcode", block=False)) is None
    (tmp_path / "cura.gcode").write_text(";FLAVOR:Klipper\n;Generated with Cura_SteamEngine 5.7\nG28\n")
    assert op.read(str(tmp_path / "cura.gcode")) is None
    assert op.read(str(tmp_path / "missing.gcode")) is None


def test_every_shape_comes_back_as_orca_keeps_it_in_a_preset(tmp_path):
    f = op.read(gcode(tmp_path / "a.gcode"))
    p = op.presets(f["block"], KEYS, 0, op.version_of(f))
    m, pr, fil = p["machine"], p["process"], p["filament"]
    assert (pr["layer_height"], pr["sparse_infill_density"], pr["enable_support"]) == ("0.2", "15%", "0")
    assert m["nozzle_diameter"] == ["0.4"] and m["machine_max_speed_x"] == ["500", "200"]
    assert m["printable_area"] == ["0x0", "300x0", "300x300", "0x300"] and m["bed_exclude_area"] == []
    assert m["bed_mesh_min"] == "-99999,-99999" and m["thumbnails"] == "48x48/PNG,300x300/PNG"
    assert m["z_hop_types"] == ["Normal Lift"]
    assert m["nozzle_type"] == "hardened_steel"                     # 2.3.1 kept it single
    assert m["extruder_colour"] == ["#FF0000"]                      # one per nozzle
    assert m["machine_start_gcode"] == 'PRINT_START BED=[bed_temperature_initial_layer_single] TOOL=[initial_tool]\nM117 "go" C:\\x'
    assert m["before_layer_change_gcode"] == ";BEFORE_LAYER_CHANGE\n;[layer_z]\nG92 E0\n"
    assert pr["small_area_infill_flow_compensation_model"] == ["0,0", "\n0.2,0.4444", "\n10,1"]
    assert fil["filament_type"] == ["PLA"] and fil["nozzle_temperature"] == ["210"]
    assert fil["default_filament_colour"] == [""] and fil["filament_start_gcode"] == ["; Filament gcode\n"]
    assert fil["filament_retraction_length"] == ["1"]
    assert fil["filament_z_hop"] == ["nil"]                         # not written when not set: nil, as Orca keeps it
    for kind, name in (("machine", "My Voron"), ("process", "0.20mm Standard @Voron"), ("filament", "Generic PLA @Voron")):
        assert p[kind]["name"] == name and p[kind]["type"] == kind and p[kind]["from"] == "User"
    assert m["printer_settings_id"] == "My Voron" and fil["filament_settings_id"] == ["Generic PLA @Voron"]
    every = {k for preset in p.values() for k in preset}
    assert not every & {"filament_colour", "curr_bed_type", "different_settings_to_system", "wipe_tower_x", "inherits"}


def test_one_filament_of_several_and_a_newer_orcas_lists(tmp_path):
    f = op.read(gcode(tmp_path / "a.gcode", generator="OrcaSlicer 2.4.2"))
    p = op.presets(f["block"], KEYS, 1, op.version_of(f))
    assert p["filament"]["name"] == "Fancy PETG @Voron" and p["filament"]["nozzle_temperature"] == ["240"]
    assert p["filament"]["filament_retraction_length"] == ["nil"]
    assert p["machine"]["nozzle_type"] == ["hardened_steel"]        # a list from 2.4.2 on


@pytest.mark.parametrize("raw,want", [
    ("", []), ("a", ["a"]), ("a;b", ["a", "b"]), (";;", ["", "", ""]), ('"a b";c', ["a b", "c"]),
    (r'"say \"hi\"";"x\\y"', ['say "hi"', "x\\y"]), (r'"one\ntwo"', ["one\ntwo"]), ('""', [""]), ("a;", ["a", ""]),
])
def test_lists_of_text_split_as_orca_splits_them(raw, want):
    assert op.split_strings(raw) == want


def test_text_unescapes_as_orca_does():
    assert op.unescape(r"G28\nG1 Z5\r\n") == "G28\nG1 Z5\r\n"
    assert op.unescape(r"M117 \"hi\" \\ done") == 'M117 "hi" \\ done'


def test_files_group_by_machine_process_nozzle_and_bed(tmp_path):
    a = gcode(tmp_path / "a.gcode", mtime=1000, used="10, 0, 0")
    b = gcode(tmp_path / "b.gcode", mtime=2000, used="0, 5, 0")
    c = gcode(tmp_path / "c.gcode", {"nozzle_diameter": "0.6"}, mtime=3000)
    d = gcode(tmp_path / "d.gcode", {"filament_settings_id": '"Newer PLA";"x";"y"'}, mtime=4000, used="1, 0, 0",
              generator="OrcaSlicer 2.4.2")
    mine = gcode(tmp_path / "e.gcode", mtime=5000, marker=True)
    files = [op.read(p) for p in (a, b, c, d, mine)]
    profiles = op.group(files)
    assert [p["nozzle"] for p in profiles] == [0.4, 0.6]           # the newest first; our own file left out
    p = profiles[0]
    assert p["files"] == 3 and p["newest"] == 4000 and p["slicer"] == "OrcaSlicer 2.4"
    assert p["slicers"] == ["OrcaSlicer 2.4", "OrcaSlicer 2.3"]
    assert (p["printer"], p["machine"], p["process"], p["bed"]) == ("Voron 2.4 300", "My Voron", "0.20mm Standard @Voron", [300.0, 300.0])
    assert p["materials"] == {"PLA": {"preset": "Newer PLA", "files": 2}, "PETG": {"preset": "Fancy PETG @Voron", "files": 1}}
    assert p["start"] == "PRINT_START" and p["plate"] == "Textured PEI Plate"
    assert p["source"] == {"machine": d, "materials": {"PLA": [d, 0], "PETG": [b, 1]}}
    assert p["id"] == op.profile_id(op.read(a)["block"]) and len(p["id"]) == 8
    assert op.agreed(profiles, files) is None                      # 3 of 4: not 80%
    assert op.agreed(profiles[:1], files) == p["id"]               # one profile: that one
    many = [op.read(gcode(tmp_path / f"m{i}.gcode", mtime=6000 + i)) for i in range(16)]
    assert op.agreed(op.group(files + many), files + many) == p["id"]   # 19 of the last 20


def test_checks_against_klipper(tmp_path):
    p = op.group([op.read(gcode(tmp_path / "a.gcode"))])[0]
    klipper = {"axis_maximum": [301.5, 299, 280, 0], "macros": ["PRINT_START", "PRINT_END"]}
    assert op.checks(p, klipper) == {"bed_ok": True, "bed_klipper": [301.5, 299.0], "start_ok": True}
    assert op.checks_pass(op.checks(p, klipper))
    small = op.checks(p, {"axis_maximum": [250, 250, 200, 0], "macros": []})
    assert small == {"bed_ok": False, "bed_klipper": [250.0, 250.0], "start_ok": False}
    assert op.checks(p, {}) == {"bed_ok": None, "bed_klipper": None, "start_ok": None}
    assert not op.checks_pass(op.checks(p, {}))
    assert op.macros_of(["gcode_macro PRINT_START", "toolhead", "gcode_macro _HOME"]) == ["PRINT_START", "_HOME"]


@pytest.mark.parametrize("start,word,ok", [
    ("PRINT_START EXTRUDER=200", "PRINT_START", True), ("; start\n\nG28\nG1 Z5", "G28", True),
    ("{if bed_temperature_initial_layer_single > 0}\nM190 S60\n{endif}", "M190", True),
    ("BED_MESH_CALIBRATE", "BED_MESH_CALIBRATE", True), ("START_PRINT BED=60", "START_PRINT", False), ("", "", True),
])
def test_the_start_gcodes_first_command(start, word, ok):
    assert op.start_word(start) == word
    got = op.checks({"bed": [300, 300], "start": word}, {"axis_maximum": [300, 300, 300], "macros": ["PRINT_START"]})
    assert got["start_ok"] is ok
