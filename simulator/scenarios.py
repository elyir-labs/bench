# ---- files with a colour change (design/colour-change/) ----------------------------------------------------
# Real G-code, the way PrusaSlicer and Orca lay it out for one spool with a colour change: layer markers,
# Klipper's SET_PRINT_STATS_INFO, and an M600 at layer 56. sim.py reads them with gcode_metadata(), which finds
# the colour changes the same way the component does. White is named, green is named, and one names nothing.
COLOUR_LAYER = 56
COLOUR_LAYERS = 140


def colour_gcode(color: str = None, at: int = COLOUR_LAYER, layers: int = COLOUR_LAYERS) -> str:
    out = ["; generated by PrusaSlicer 2.8.1 (the simulator's stand-in)",
           "; estimated printing time (normal mode) = 1h 40m 0s",
           "; filament_colour = #D9534F", "; filament_type = PLA", "; filament used [g] = 33.00",
           "; total filament used [g] = 33.00", f"; total layer number: {layers}", "; layer_height = 0.2",
           "; color_change_gcode = M600",
           "PRINT_START BED=60 EXTRUDER=215 CHAMBER=0", "SET_PRINT_STATS_INFO TOTAL_LAYER_COUNT=%d" % layers]
    for n in range(1, layers + 1):
        out += [";LAYER_CHANGE", f";Z:{n * 0.2:.1f}", ";HEIGHT:0.2", f"SET_PRINT_STATS_INFO CURRENT_LAYER={n}"]
        if n == at:
            out += [f";COLOR_CHANGE,T0,{color}" if color else ";COLOR_CHANGE", "M600"]
        out += ["G1 X120 Y140 E1.2 F1800", "G1 X140 Y140 E1.2"]
    out += ["PRINT_END", "; end of print"]
    return "\n".join(out) + "\n"


