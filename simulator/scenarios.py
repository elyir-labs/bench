async def _move(sim, points, seconds: float) -> None:
    """The head along a path of (x, y, z), at an even speed, reported four times a second
    the way motion_report's live_position is."""
    pts = [tuple(float(v) for v in p) for p in points]
    lens = [sum((b[i] - a[i]) ** 2 for i in range(3)) ** 0.5 for a, b in zip(pts, pts[1:])]
    total = sum(lens) or 1.0
    n = max(1, int(seconds * 4))
    for k in range(n + 1):
        d, seg = total * k / n, 0
        while seg < len(lens) - 1 and d > lens[seg]:
            d -= lens[seg]
            seg += 1
        a, b = pts[seg], pts[min(seg + 1, len(pts) - 1)]
        f = 0.0 if not lens or not lens[seg] else min(1.0, d / lens[seg])
        sim.patch({"motion_report": {"live_position": [round(a[i] + (b[i] - a[i]) * f, 2) for i in range(3)] + [0.0]}})
        if k < n:
            await sim.sleep(seconds / n)


async def print_job(sim, filename: str = "phone_stand_0.2mm_PLA_MK4_1h40m.gcode", runout_at: float = -1, **_) -> None:
    """Start a print: PRINT_START steps, then printing. Optionally runs out of filament part way."""
    meta = FILES.get(filename, {})
    bed, noz = meta.get("first_layer_bed_temp", 60), meta.get("first_layer_extr_temp", 215)
    sim.patch({"exclude_object": {"objects": OBJECTS.get(filename, []), "excluded_objects": [], "current_object": None}})
    sim.set_file(filename)
    sim.patch({"print_stats": {"state": "printing", "filename": filename, "print_duration": 0.0, "total_duration": 0.0,
                               "message": "", "info": {"current_layer": None, "total_layer": None}},
               "virtual_sdcard": {"progress": 0.0, "is_active": True},
               "idle_timeout": {"state": "Printing"}})
    # Workshop's shared PRINT_START: a stage per step in gcode_macro _PRINT_START (the ring draws it),
    # the older M117 words alongside, and the head moving the way it does on the printer.
    def stage(name, message):
        sim.patch({"gcode_macro _PRINT_START": {"stage": name}, "display_status": {"message": message}})

    stage("warming", "Pre-heating bed and toolhead...")
    sim.patch({"heater_bed": {"target": bed}, "extruder": {"target": 150}})
    await sim.sleep(40)
    stage("soaking", "Heat-soaking bed to %dC for 10 min..." % bed)
    await sim.sleep(60)
    stage("home", "Homing...")
    sim.patch({"toolhead": {"homed_axes": "xyz"}})
    await _move(sim, [(300, 300, 30), (350, 350, 30), (175, 175, 12), (175, 175, 1), (175, 175, 12)], 12)
    stage("qgl", "Leveling Gantry ........")
    corners = [(40, 40), (40, 310), (310, 310), (310, 40)]
    for rng in (0.4125, 0.0563, 0.0041):
        await _move(sim, [(x, y, 6) for x, y in corners], 10)
        sim.gcode_response(f"// Retries: 0/5 Probed points range: {rng:.6f} tolerance: 0.007500")
    stage("mesh", "Calibrating mesh ........")
    rows = [20, 100, 175, 250, 330]
    path = []
    for k, y in enumerate(rows):
        path += [(20, y, 2), (330, y, 2)] if k % 2 == 0 else [(330, y, 2), (20, y, 2)]
    await _move(sim, path, 30)
    stage("home_again", "Homing...")
    await _move(sim, [(20, 330, 2), (175, 175, 10)], 6)
    stage("heating", "Heating Toolhead")
    sim.patch({"extruder": {"target": noz}})
    await sim.sleep(25)
    stage("prime", "Purging...")
    await _move(sim, [(20, 8, 0.3), (190, 8, 0.3)], 8)
    sim.apply_first_layer()
    sim.patch({"gcode_macro _PRINT_START": {"stage": ""}})
    sim.patch({"display_status": {"message": "Printing, good luck!"}})
    sim.gcode_response("// Printing, good luck!")
    if meta.get("colour_changes"):
        await _colour_changes(sim, filename)
        return
    if runout_at > 0:
        while sim.status["virtual_sdcard"]["progress"] < runout_at and sim.status["print_stats"]["state"] == "printing":
            await sim.sleep(1)
        if sim.status["print_stats"]["state"] != "printing":
            return
        # The white spool (slot 1) runs dry mid-print
        sim.patch({"ace": {"selected_gate": 1}})
        await run_out(sim, 1)


async def run_out(sim, g: int) -> None:
    """Slot g runs dry mid-print, the way KlipperACE handles it: pause, then carry on with a
    same-colour, same-material spool by itself when endless spool is on, else wait for a person."""
    sim.set_slot(g, replace=True, status="empty")
    sim.patch({"pause_resume": {"is_paused": True}, "print_stats": {"state": "paused"}})
    alt = sim.endless_match(g) if sim.status["ace"].get("endless_spool") else None
    if alt is None:
        sim.gcode_response("Spool is empty")
        sim.gcode_response("Filament runout! Endless spool disabled" if not sim.status["ace"].get("endless_spool")
                           else f"Filament runout on T{g}! No matching spools available")
        await sim.wait_for("resume")
        return
    sim.gcode_response(f"Endless spool: T{g} empty, switching to T{alt}")
    sim.gcode_response(f"// ACE: Loading tool {alt}...")
    await sim.sleep(20)
    sim.patch({"ace": {"selected_gate": alt}})
    sim.gcode_response("// RESUME")
    sim.patch({"pause_resume": {"is_paused": False}, "print_stats": {"state": "printing"}})


async def day(sim, **_) -> None:
    """A full day: ready, a print that runs out of white part way (carry-on off), finished, ready again."""
    sim.patch({"ace": {"endless_spool": False}})
    await sim.sleep(8)
    await print_job(sim, runout_at=0.4)
    while sim.status["print_stats"]["state"] in ("printing", "paused"):
        await sim.sleep(2)
    # print completes in physics(); cool the bed down for the finished countdown
    while sim.status["print_stats"]["state"] == "complete" and sim.status["heater_bed"]["temperature"] > 30:
        await sim.sleep(5)


async def idle(sim, **_) -> None:
    """Nothing happening. Ready screen with spools loaded."""
    sim.tracker.acknowledge_finished()
    sim.patch({"print_stats": {"state": "standby", "filename": ""}, "pause_resume": {"is_paused": False},
               "heater_bed": {"target": 0.0}, "extruder": {"target": 0.0}, "idle_timeout": {"state": "Idle"}})


async def hot(sim, **_) -> None:
    """Ready, with the nozzle still at printing heat (design/power/: Turn off waits for it to cool)."""
    await idle(sim)
    sim.patch({"extruder": {"temperature": 205.0, "target": 205.0}, "heater_bed": {"temperature": 60.0, "target": 60.0}})


async def print_(sim, filename: str = None, **_) -> None:
    """Start a print that goes all the way through without incident."""
    await print_job(sim, filename or "phone_stand_0.2mm_PLA_MK4_1h40m.gcode")


async def runout(sim, **_) -> None:
    """Jump to a print that is already at 40% and runs out of white right now (carry-on off)."""
    filename = "phone_stand_0.2mm_PLA_MK4_1h40m.gcode"
    if not sim.ace:
        # One spool: the toolhead sensor sees the end of it and pauses, the way Desk's does.
        sim.set_file(filename)
        sim.patch({"print_stats": {"state": "printing", "filename": filename, "print_duration": 2400.0, "total_duration": 2500.0,
                                   "info": {"current_layer": 56, "total_layer": 140}},
                   "virtual_sdcard": {"progress": 0.4, "is_active": True},
                   "heater_bed": {"temperature": 60.0, "target": 60.0}, "extruder": {"temperature": 215.0, "target": 215.0, "can_extrude": True},
                   "display_status": {"message": "Printing, good luck!"}, "idle_timeout": {"state": "Printing"},
                   "toolhead": {"homed_axes": "xyz"}})
        await sim.sleep(3)
        sim.patch({SENSOR: {"filament_detected": False}})
        sim.gcode_response("// Filament runout detected (Toolhead)")
        sim.patch({"pause_resume": {"is_paused": True}, "print_stats": {"state": "paused"}})
        await sim.wait_for("resume")
        return
    sim.set_file(filename)
    sim.patch({"print_stats": {"state": "printing", "filename": filename, "print_duration": 2400.0, "total_duration": 2500.0,
                               "info": {"current_layer": 56, "total_layer": 140}},
               "virtual_sdcard": {"progress": 0.4, "is_active": True},
               "heater_bed": {"temperature": 60.0, "target": 60.0}, "extruder": {"temperature": 215.0, "target": 215.0, "can_extrude": True},
               "display_status": {"message": "Printing, good luck!"}, "idle_timeout": {"state": "Printing"},
               "toolhead": {"homed_axes": "xyz"}, "ace": {"selected_gate": 1, "endless_spool": False}})   # carry-on off, as it says
    sim.gcode_response("// Printing, good luck!")
    await sim.sleep(3)
    await run_out(sim, 1)


