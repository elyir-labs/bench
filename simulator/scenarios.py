# ---- one spool: a printer without a filament unit (run the simulator with --no-ace) ----

SENSOR = "filament_switch_sensor extruder_sensor"


async def _spool(sim, color=None, material=None, source="told", days=3.0, filename=None, head=True):
    import time as _t
    await idle(sim)
    sim.tracker.direct_spool = None
    if material:
        sim.tracker.remember_spool(color, material, source, now=_t.time() - days * 86400, filename=filename)
    else:
        sim.tracker.direct_spool_dirty = True   # forget it in the "database" too
    sim.patch({SENSOR: {"filament_detected": head}})


async def spool_unknown(sim, **_) -> None:
    """One spool, and nobody has said what it is."""
    await _spool(sim)


async def spool_told(sim, **_) -> None:
    """One spool: black PETG, said three days ago."""
    await _spool(sim, "#1E1E1E", "PETG")


async def spool_guess(sim, **_) -> None:
    """One spool: probably blue PLA, going by the last print (Benchy)."""
    await _spool(sim, "#3B82F6", "PLA", source="guess", days=0.2, filename="Benchy.gcode")


async def spool_empty(sim, **_) -> None:
    """One spool's worth of nothing: the head sensor says it's empty; it was white PLA."""
    await _spool(sim, "#F1F1F1", "PLA", head=False)


async def spool_changed(sim, **_) -> None:
    """White PLA was on; the filament comes out of the head and something goes back in."""
    await _spool(sim, "#F1F1F1", "PLA")
    await sim.sleep(4)
    sim.patch({SENSOR: {"filament_detected": False}})
    await sim.sleep(8)
    sim.patch({SENSOR: {"filament_detected": True}})


async def spool_spoolman(sim, **_) -> None:
    """Spoolman is set up and its active spool is orange PETG with 640 g left."""
    await _spool(sim)
    sim.tracker.spoolman_spool = {"color": "FF8800", "material": "PETG", "grams": 640}
    sim.publish(force=True)


