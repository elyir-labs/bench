async def _upload(client, name, body):
    from aiohttp import FormData
    form = FormData()
    form.add_field("model", body, filename=name)
    r = await client.post("/slice/models", data=form)
    assert r.status == 201, await r.text()
    return await r.json()


async def _done(client, jid):
    import asyncio
    for _ in range(600):
        d = await (await client.get(f"/slice/{jid}")).json()
        if d["state"] in ("done", "failed"):
            return d
        await asyncio.sleep(0.2)
    raise AssertionError("never finished")


@pytest.mark.skipif(not os.path.exists(REAL_ORCA), reason="OrcaSlicer isn't installed here")
async def test_service_a_part_in_each_color_one_by_hand(real):
    a = await _upload(real, "a.stl", _cube_stl(20).encode())
    b = await _upload(real, "b.stl", _cube_stl(15).encode())
    r = await real.post("/slice", json={
        "printer": "v", "purpose": "draft",
        "parts": [{"model": a["model"], "spool": 0}, {"model": b["model"], "spool": 1}],
        "spools": [{"material": "ASA", "color": WHITE, "slot": 3}, {"material": "ASA", "color": GOLD, "hand": True}],
    })
    assert r.status == 202, await r.text()
    d = await _done(real, (await r.json())["id"])
    assert d["state"] == "done", d.get("error_detail") or d.get("error")
    assert d["request"]["purge"] == "chute" and d["request"]["spools"][1]["hand"] is True
    colors = d["colors"]
    assert colors["hand_swaps"] > 5 and colors["spools"][0]["parts"] == [0] and colors["spools"][1]["parts"] == [1]
    assert len(colors["grams"]) == 2 and d["estimate"]["changes_seconds"] == len(colors["changes"]) * 105
    body = await (await real.get(f"/slice/{d['id']}/gcode")).text()
    # Orca's own Voron start G-code passes no TOOL=, so the first color is loaded by its T after PRINT_START
    assert "TOOL=" not in body.split("; CONFIG_BLOCK_START")[0] and "\nT2\n" in body
    assert "\nM600\n" in body and f";COLOR_CHANGE,T1,{GOLD}" in body


