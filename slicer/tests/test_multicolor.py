def test_spools_need_slots_of_their_own(printer):
    ok = spools((WHITE, 1, False), (BLUE, 3, False), (GOLD, None, True))
    assert sl.spool_problems(printer, ok, None) == []
    assert "colors 1 and 2 both come from slot 2" in sl.spool_problems(printer, spools((WHITE, 1, False), (BLUE, 1, False)), None)
    assert "color 2: slot must be 1 to 8" in sl.spool_problems(printer, spools((WHITE, 1, False), (BLUE, 8, False)), None)


def test_purge_fits_the_printer(printer):
    two = spools((WHITE, 1, False), (BLUE, 3, False))
    assert f"{printer.name} has no purge chute" in sl.spool_problems(printer, two, "chute")
    printer.purge = "chute"
    assert sl.spool_problems(printer, two, "both") == []
    assert any("At the swap" in p for p in sl.spool_problems(printer, two, "swap"))
    assert sl.spool_problems(printer, spools((WHITE, 1, False), (GOLD, None, True)), "swap") == []
    assert "purge must be one of chute, tower, both, swap" in sl.spool_problems(printer, two, "poop")


