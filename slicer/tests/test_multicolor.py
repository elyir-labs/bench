def _three_mf(path, model_extra="", files=None):
    model = ('<?xml version="1.0" encoding="UTF-8"?><model unit="millimeter" '
             'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><resources><object id="1" type="model"><mesh>'
             '<vertices><vertex x="0" y="0" z="0"/><vertex x="10" y="0" z="0"/><vertex x="0" y="10" z="0"/><vertex x="0" y="0" z="10"/></vertices>'
             f'<triangles><triangle v1="0" v2="2" v3="1"{model_extra}/><triangle v1="0" v2="1" v3="3"/><triangle v1="0" v2="3" v3="2"/>'
             '<triangle v1="1" v2="2" v3="3"/></triangles></mesh></object></resources>'
             '<build><item objectid="1"/></build></model>')
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("3D/3dmodel.model", model)
        for name, data in (files or {}).items():
            z.writestr(name, data)
    return str(path)


