# ── the G-code ───────────────────────────────────────────────────────────────

ORCA_LIKE = """; generated by OrcaSlicer
M73 P0 R26
PRINT_START EXTRUDER=250 BED=105 TOOL=0
ELYIR_PURGE LENGTH=0 FROM=-1 TO=0
T0
;LAYER_CHANGE
G1 X1 E1
M73 P10 R23
;LAYER_CHANGE
ELYIR_PURGE LENGTH=98.5332 FROM=0 TO=1
T1
G1 X2 E1
M73 P50 R13
;LAYER_CHANGE
ELYIR_PURGE LENGTH=163.39 FROM=1 TO=2
T2
G1 X3 E1
"""


def test_slots_and_swaps_by_hand(tmp_path, printer):
    g = tmp_path / "plate_1.gcode"
    g.write_text(ORCA_LIKE)
    printer.purge = "chute"
    got = sl.assign_spools(str(g), spools((WHITE, 1, False), (BLUE, 3, False), (GOLD, None, True)), printer, "chute")
    text = g.read_text()
    assert "PRINT_START EXTRUDER=250 BED=105 TOOL=1" in text
    assert "FROM=" not in text
    assert text.index("TOOL=1") < text.index("\nT1\n") < text.index(";LAYER_CHANGE")     # the first color, loaded after the start
    assert "ELYIR_PURGE LENGTH=98.5\nT3\n" in text
    assert ";COLOR_CHANGE,T2,#C9A227\n; elyir: by hand\nM600\n" in text
    assert got["first"] == 0
    assert got["changes"] == [
        {"layer": 2, "at": 180, "to": 1, "hand": False, "purge": 98.5},
        {"layer": 3, "at": 780 + 105, "to": 2, "hand": True, "purge": 163.4},
    ]


